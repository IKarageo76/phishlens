"""Case-note and IOC exports. All indicators are defanged so the output is safe to paste."""

import csv
import io

from app.core.util import defang
from app.models.schemas import Report, SourceStatus

STATUS_TEXT = {"hit": "Flagged", "clean": "Clean", "info": "Info", "skipped": "Not checked", "error": "Failed"}
SOURCE_TITLES = {
    "virustotal": "VirusTotal", "abuseipdb": "AbuseIPDB", "urlscan": "urlscan.io", "urlhaus": "URLhaus",
    "threatfox": "ThreatFox", "malwarebazaar": "MalwareBazaar", "safebrowsing": "Google Safe Browsing",
    "spamhaus": "Spamhaus", "otx": "AlienVault OTX", "phishstats": "PhishStats", "stopforumspam": "StopForumSpam",
    "hibp": "Have I Been Pwned", "circl": "CIRCL hashlookup", "internetdb": "Shodan InternetDB", "ipinfo": "IPinfo",
    "dns": "DNS", "rdap": "RDAP",
}

LABELS = {
    "likely_legitimate": "Likely legitimate",
    "suspicious": "Suspicious",
    "malicious": "Malicious",
}


def case_note(report: Report) -> str:
    v = report.verdict
    lines = [
        f"# Email triage: {LABELS[v.label.value]} ({v.score}/100)",
        "",
        f"- **Input:** {defang(report.input_value) if report.input_type != 'eml' else report.input_value}",
        f"- **Analysed:** {report.created_at:%Y-%m-%d %H:%M} UTC",
        f"- **Confidence:** {v.confidence} ({v.sources_run} sources ran, {v.sources_skipped} skipped)",
        f"- **Report ID:** {report.id}",
    ]
    h = report.headers
    if h:
        lines += [
            "",
            "## Message",
            f"- **Subject:** {h.subject or '-'}",
            f"- **From:** {h.from_display or ''} <{defang(h.from_address) if h.from_address else '-'}>",
            f"- **Reply-To:** {defang(h.reply_to) if h.reply_to else '-'}",
            f"- **Return-Path:** {defang(h.return_path) if h.return_path else '-'}",
            f"- **Authentication:** SPF={h.auth.spf or 'none'}, DKIM={h.auth.dkim or 'none'}, DMARC={h.auth.dmarc or 'none'}",
            f"- **Origin IP:** {defang(h.origin_ip) if h.origin_ip else '-'}",
        ]
    lines += ["", "## Why", ""]
    if report.signals:
        lines += ["| Signal | Points | Evidence |", "| --- | --- | --- |"]
        for s in report.signals:
            lines.append(f"| {s.label} | {s.weight:+d} | {defang_text(s.evidence)} |")
    else:
        lines.append("No risk signals were found.")
    hits = [r for r in report.results if r.status == SourceStatus.hit]
    if hits:
        lines += ["", "## Threat intelligence hits", ""]
        for r in hits:
            lines.append(f"- **{r.source}** - {defang(r.indicator.value)}: {r.summary}")
    if report.links:
        lines += ["", "## Links", ""]
        for l in report.links:
            flags = ", ".join(f for f, on in (("deceptive", l.deceptive), ("shortener", l.is_shortener)) if on)
            lines.append(f"- `{l.defanged}`" + (f" ({flags})" if flags else ""))
    if report.attachments:
        lines += ["", "## Attachments", "", "| File | Type | SHA-256 | Notes |", "| --- | --- | --- | --- |"]
        for a in report.attachments:
            lines.append(f"| {a.filename} | {a.detected_type} | `{a.sha256}` | {'; '.join(a.reasons) or '-'} |")
    lines += ["", "## Evidence", "",
              "Each row is the result as returned by the source at the time shown. Open the link to verify it at the source.", "",
              "| Source | Indicator | Result | Checked (UTC) | Verify |", "| --- | --- | --- | --- | --- |"]
    order = {SourceStatus.hit: 0, SourceStatus.info: 1, SourceStatus.clean: 2, SourceStatus.error: 3, SourceStatus.skipped: 4}
    for r in sorted(report.results, key=lambda x: (order[x.status], x.source)):
        when = f"{r.checked_at:%Y-%m-%d %H:%M}" if r.checked_at else "-"
        if r.cached:
            when += " (cached)"
        status = STATUS_TEXT[r.status.value]
        summary = r.summary.replace("|", "/")
        link = f"[open]({r.link})" if r.link else "-"
        value = r.indicator.value if r.indicator.type.value == "hash" else defang(r.indicator.value)
        lines.append(f"| {SOURCE_TITLES.get(r.source, r.source)} | `{value}` | {status}: {summary} | {when} | {link} |")
    lines += ["", "_Generated by PhishLens. Indicators are defanged; verification links point to the source's own site._", ""]
    return "\n".join(lines)


def defang_text(text: str) -> str:
    out = []
    for token in text.split(" "):
        stripped = token.strip("()',")
        if ("." in stripped and ("/" in stripped or stripped.count(".") >= 1) and not stripped.endswith(".")
                and any(c.isalpha() for c in stripped.split(".")[-1])):
            token = token.replace(stripped, defang(stripped))
        out.append(token)
    return " ".join(out)


def iocs_csv(report: Report) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["type", "value_defanged", "origin", "verdict_sources"])
    hits: dict[str, list[str]] = {}
    for r in report.results:
        if r.status == SourceStatus.hit:
            hits.setdefault(r.indicator.key, []).append(r.source)
    for ind in report.indicators:
        w.writerow([ind.type.value, defang(ind.value) if ind.type.value != "hash" else ind.value, ind.origin,
                    ";".join(hits.get(ind.key, []))])
    return buf.getvalue()
